def apply_fixes():
    # 1. Update dev.jsonl
    with open('evals/datasets/dev.jsonl', 'r', encoding='utf-8') as f:
        dev_rows = [json.loads(line) for line in f if line.strip()]

    dev_updated = 0
    for r in dev_rows:
        qid = r['id']
        if qid in DEV_REPLACEMENTS:
            old_q, new_q = DEV_REPLACEMENTS[qid]
            r['question'] = new_q
            dev_updated += 1

    with open('evals/datasets/dev.jsonl', 'w', encoding='utf-8') as f:
        for r in dev_rows:
            f.write(json.dumps(r) + '\n')

    # 2. Update test.jsonl and stratify
    with open('evals/datasets/test.jsonl', 'r', encoding='utf-8') as f:
        test_rows = [json.loads(line) for line in f if line.strip()]

    test_updated = 0
    for r in test_rows:
        qid = r['id']
        if qid in TEST_REPLACEMENTS:
            old_q, new_q = TEST_REPLACEMENTS[qid]
            r['question'] = new_q
            test_updated += 1

    # Stratify / interleave test questions: easy, medium, hard round-robin
    easy_q = [r for r in test_rows if r['difficulty'] == 'easy']
    med_q = [r for r in test_rows if r['difficulty'] == 'medium']
    hard_q = [r for r in test_rows if r['difficulty'] == 'hard']

    stratified_test = []
    max_len = max(len(easy_q), len(med_q), len(hard_q))
    for i in range(max_len):
        if i < len(easy_q):
            stratified_test.append(easy_q[i])
        if i < len(med_q):
            stratified_test.append(med_q[i])
        if i < len(hard_q):
            stratified_test.append(hard_q[i])

    assert len(stratified_test) == len(test_rows) == 100

    with open('evals/datasets/test.jsonl', 'w', encoding='utf-8') as f:
        for r in stratified_test:
            f.write(json.dumps(r) + '\n')

    # Calculate SHA-256
    with open('evals/datasets/dev.jsonl', 'rb') as f:
        dev_hash = hashlib.sha256(f.read()).hexdigest()
    with open('evals/datasets/test.jsonl', 'rb') as f:
        test_hash = hashlib.sha256(f.read()).hexdigest()

    print(f"Updated {dev_updated} dev questions. dev.jsonl SHA-256: {dev_hash}")
    print(f"Updated {test_updated} test questions and stratified 100 items. test.jsonl SHA-256: {test_hash}")

if __name__ == '__main__':
    apply_fixes()
